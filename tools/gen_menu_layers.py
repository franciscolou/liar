# The lantern: the flame is the light above the glow of the glass, kept as a
# layer of its own to be added back (plate + flame = the painting).

GLASS = (84, 282, 152, 364)  # x0, y0, x1, y1
FLAME_COLUMNS = (99, 133)
FLAME_LUMA = 190.0


def split_flame(a):
	x0, y0, x1, y1 = GLASS
	l = lum(a)
	hot = np.zeros(l.shape, bool)
	hot[y0:y1, FLAME_COLUMNS[0]:FLAME_COLUMNS[1]] = l[y0:y1, FLAME_COLUMNS[0]:FLAME_COLUMNS[1]] > FLAME_LUMA
	labels, _ = ndimage.label(hot)
	hot = labels == labels[337, 115]
	hot = ndimage.binary_dilation(hot, iterations=1)
	plate = cv2.inpaint(np.round(a).astype(np.uint8), hot.astype(np.uint8), 5, cv2.INPAINT_TELEA).astype(float)
	plate[~hot] = a[~hot]
	# Never brighter than the painting, or adding the flame back overshoots.
	plate = np.minimum(np.round(plate), a)
	flame = np.clip(a - plate, 0, 255)
	flame[~hot] = 0
	return plate, flame[y0:y1, x0:x1]


