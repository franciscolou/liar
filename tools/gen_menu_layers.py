def cut_man(clean):
	shape = clean.shape
	hand = poly_mask(shape, HAND)
	fore = poly_mask(shape, FOREARM)
	cuff = poly_mask(shape, CUFF)
	for x0, y0, x1, y1 in BUTTONS:
		cuff[y0:y1, x0:x1] = True
	# Every bright bit of the cuff and the watch.
	cuff |= fore & (lum(clean) > 40.0)
	fore |= ndimage.binary_dilation(cuff, iterations=2)
	jaw = poly_mask(shape, JAW)
	# The edge of the hand is a pixel or two of it blended into what is
	# behind. That rim leaves the plate too, but not with the hand (it would
	# drag a line of his face along): it is a sprite of its own, shown only
	# while the hand is where the painting has it.
	rim = ndimage.binary_dilation(hand, iterations=2) & ~hand & ~fore
	gone = hand | fore & ndimage.binary_dilation(cuff, iterations=2) | rim
	bare = clean.copy()
	# The room behind the hand: whatever is nearest, never his face.
	room = nearest_fill(bare, gone | jaw | (lum(bare) > 40.0))
	# Above the chair it is the wall, plank by plank; the dark of the chair
	# under that.
	yy, xx = np.mgrid[0:shape[0], 0:shape[1]]
	wall = column_fill(bare, gone | jaw)
	rng = np.random.default_rng(11)
	dark = np.array([7.0, 4.0, 2.0]) * (0.6 + cv2.GaussianBlur(blocky_noise(shape[:2], 4, rng), (0, 0), 1.5))[..., None]
	fade = np.clip((yy - 298) / 20.0, 0.0, 1.0)[..., None]
	room = np.where(((yy < 348) & (xx < 512))[..., None], wall * (1.0 - fade) + dark * fade, room)
	# Behind the cuff there is only the dark of his jacket.
	room = np.where(((yy >= 392) & (xx >= 496))[..., None], dark, room)
	bare[gone & ~jaw] = room[gone & ~jaw]
	paint_face(bare, gone & jaw)
	return bare, hand, fore, rim


def sprite(name, a, mask, pad=0):
	"""Saves the pixels of `mask` cropped to its box, with `pad` empty pixels
	above (room for the sprite to rise into); returns the box."""
	ys, xs = np.nonzero(mask)
	x0, y0, x1, y1 = xs.min(), ys.min() - pad, xs.max() + 1, ys.max() + 1
	save(name, a[y0:y1, x0:x1], alpha=mask[y0:y1, x0:x1].astype(float))
	return int(x0), int(y0), int(x1), int(y1)


def strip(name, frames, alphas=None):
	"""Saves frames side by side (hframes of a Sprite2D)."""
	a = np.hstack(frames)
	save(name, a, alpha=None if alphas is None else np.hstack(alphas))


def eye_frames(bare):
	"""Open, half shut, shut, looking left, looking right, for each eye.

	The eyes of the painting are two black slits with a catchlight each, so
	that is what moves: the catchlight slides, a dim white shows on the side
	it left, and the lid comes down over it in the tone of the lid above."""
	lid_l, lid_r = np.array([40.0, 15.0, 3.0]), np.array([52.0, 21.0, 6.0])
	white = np.array([44.0, 27.0, 18.0])
	black = np.zeros(3)
	out = []
	for box, glints, slit, lid in (
			(EYE_L, [(382, 266, 2, 2)], (370, 264, 26, 8), lid_l),
			(EYE_R, [(436, 256, 4, 2), (426, 256, 2, 2)], (422, 252, 26, 6), lid_r)):
		x0, y0, x1, y1 = box
		lights = [bare[y:y + h, x:x + w].copy() for x, y, w, h in glints]

		def frame(shift=0, lid_rows=0, dim=1.0):
			f = bare.copy()
			for x, y, w, h in glints:
				f[y:y + h, x:x + w] = black
			gx, gy, gw, gh = glints[0]
			f[gy:gy + gh, gx + shift:gx + shift + gw] = lights[0] * dim
			if shift != 0:
				# The white of the eye, on the side the iris left.
				wx = gx - shift * 2 + (gw if shift < 0 else -2)
				f[gy:gy + 2, wx:wx + 2] = white
			if len(glints) > 1 and shift <= 0:
				x, y, w, h = glints[1]
				f[y:y + h, x:x + w] = lights[1] * dim * (0.6 if shift < 0 else 1.0)
			# The lid comes down over the dark of the eye and nothing else;
			# shut, the lashes are the last line of it.
			sx, sy, sw, sh = slit
			dark = np.zeros(bare.shape[:2], bool)
			dark[sy:sy + sh, sx:sx + sw] = lum(bare[sy:sy + sh, sx:sx + sw]) < 14.0
			for x, y, w, h in glints:
				dark[y:y + h, x:x + w] = True
			rows = np.cumsum(dark, axis=0)
			total = rows[-1][None, :]
			shut = dark & (rows <= np.maximum(total - 2, 0) if lid_rows >= sh else rows <= lid_rows)
			f[shut] = lid
			if lid_rows >= sh:
				f[dark & ~shut] = black
			return f[y0:y1, x0:x1]

		out.append([frame(), frame(lid_rows=2, dim=0.6), frame(lid_rows=slit[3]), frame(-3), frame(3)])
	return out


def ember_frames(a):
	"""The burning tip: as painted, glowing and white-hot. Plus its halo."""
	x0, y0, x1, y1 = EMBER
	crop = a[y0:y1, x0:x1]
	r, g, b = crop[..., 0], crop[..., 1], crop[..., 2]
	hot = (r > 110) & (r > b * 1.7) & (np.arange(x0, x1)[None, :] >= 500)
	frames, alphas = [], []
	for heat in (0.0, 0.5, 1.0):
		lit = hot if heat == 0.0 else ndimage.binary_dilation(hot, iterations=1 if heat < 1.0 else 2)
		f = nearest_fill(crop, ~hot)
		f = f + (np.array([255.0, 232.0, 150.0]) - f) * heat * 0.75
		f[lit & ~hot] *= 0.8
		frames.append(f)
		alphas.append(lit.astype(float) * (1.0 if heat else 0.0))
	strip("ember.png", frames, alphas)
	# The halo, in rings.
	n = 64
	yy, xx = np.mgrid[0:n, 0:n]
	d = np.hypot(np.floor(xx / 2) * 2 + 1 - n / 2, np.floor(yy / 2) * 2 + 1 - n / 2) / (n / 2)
	rings = np.floor(np.clip(1.0 - d, 0, 1) ** 2 * 5) / 5
	save("ember_glow.png", rings[..., None] * np.array([255.0, 120.0, 40.0]))


