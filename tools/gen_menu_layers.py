# Where the light of the room varies. R: how much of the lantern reaches the
# pixel. G: metal that glints on its own. B: the lit windows far away.

LANTERN = (116, 332)


def light_mask(a):
	h, w = a.shape[:2]
	yy, xx = np.mgrid[0:h, 0:w]
	l = lum(a)
	reach = np.exp(-np.hypot(xx - LANTERN[0], yy - LANTERN[1]) / 420.0)
	reach *= np.clip((SKY[0] - xx) / 60.0, 0, 1)
	r, g, b = a[..., 0], a[..., 1], a[..., 2]
	gold = (l > 70) & (g > b * 2.2) & (r > g * 1.15) & (g > r * 0.55)
	gold &= np.hypot(xx - LANTERN[0], yy - LANTERN[1]) > 150
	gold &= xx < SKY[0]
	gold = ndimage.binary_opening(gold, iterations=1)
	windows = (xx > SKY[0]) & (l > 60) & (r > b * 1.6) & (yy > 250)
	windows = ndimage.binary_dilation(windows, iterations=2)
	return np.dstack([reach, gold.astype(float), windows.astype(float)]) * 255


