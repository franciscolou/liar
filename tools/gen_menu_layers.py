# The painted smoke of the cigar: taken off the wall (the game draws its own).

SMOKE_AREA = [(418, 44), (500, 44), (500, 86), (562, 86), (562, 225), (558, 225), (558, 292), (520, 292),
		(520, 290), (478, 290), (478, 236), (470, 205), (452, 172), (418, 168)]
# Stretches of wall around it that the smoke never reached (x0, y0, x1, y1).
CLEAR_WALL = [(418, 24, 562, 42), (404, 86, 416, 164), (562, 86, 567, 220), (518, 293, 556, 297),
		(532, 264, 556, 290)]


def remove_smoke(a):
	area = poly_mask(a.shape, SMOKE_AREA)
	l = lum(a)
	# The planks run straight down, so the wall of each column is the wall
	# above the smoke times how much brighter the wall gets on the way down,
	# and that is read from the clear wall around and spread over the area.
	top = np.median(a[24:42], axis=0)
	planks = lum(top) > 4.0
	# The gaps between planks are not black all the way down.
	top[~planks] = np.array([3.0, 1.5, 1.0])
	gain = l / lum(top)[None, :]
	known = np.zeros(l.shape, bool)
	for x0, y0, x1, y1 in CLEAR_WALL:
		known[y0:y1, x0:x1] = True
	known &= planks[None, :]
	spread = cv2.GaussianBlur(np.where(known, gain, 0.0), (0, 0), 30)
	spread /= np.maximum(cv2.GaussianBlur(known.astype(float), (0, 0), 30), 1e-6)
	rng = np.random.default_rng(7)
	grain = 1.0 + (blocky_noise(l.shape, 2, rng) - 0.5) * 0.25
	blotch = 1.0 + (cv2.GaussianBlur(blocky_noise(l.shape, 6, rng), (0, 0), 3) - 0.5) * 0.5
	wall = top[None, :, :] * (spread * grain * blotch)[..., None]
	# Smoke only ever brightens: whatever is darker than the wall is kept.
	smoke = area & (l > lum(wall))
	out = a.copy()
	out[smoke] = wall[smoke]
	return out, smoke


