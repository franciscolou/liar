"""Cuts assets/StartScreen.png into the layers the animated title screen uses.

The painting itself is never touched: everything in assets/menu/ is derived
from it and can be regenerated by running this again.

    pip install numpy scipy opencv-python-headless pillow
    python tools/gen_menu_layers.py [--debug DIR]

Coordinates are pixels of the painting (1672x941). The numbers the game needs
(where each sprite goes, the pivots of the rig) are in scripts/ui/menu_scene.gd
and have to follow the ones here.
"""
import os
