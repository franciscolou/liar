ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "assets", "StartScreen.png")
OUT = os.path.join(ROOT, "assets", "menu")
DEBUG = sys.argv[sys.argv.index("--debug") + 1] if "--debug" in sys.argv else ""

LUMA = np.array([0.3, 0.59, 0.11])


def lum(a):
	return a @ LUMA


def poly_mask(shape, points):
	"""A boolean mask of the polygon `points` [(x, y), ...]."""
	m = Image.new("L", (shape[1], shape[0]), 0)
	ImageDraw.Draw(m).polygon(points, fill=255)
	return np.asarray(m) > 0


def nearest_fill(a, hole):
	"""Every pixel of `hole` takes the colour of the nearest pixel outside it."""
	idx = ndimage.distance_transform_edt(hole, return_distances=False, return_indices=True)
	out = a.copy()
	out[hole] = a[idx[0][hole], idx[1][hole]]
	return out


def column_fill(a, hole):
	"""Every pixel of `hole` takes the nearest pixel outside it in its own column."""
	out = a.copy()
	for x in np.unique(np.nonzero(hole)[1]):
		col = hole[:, x]
		free = np.nonzero(~col)[0]
		if len(free) == 0:
			continue
		ys = np.nonzero(col)[0]
		pos = np.clip(np.searchsorted(free, ys), 1, len(free) - 1)
		above, below = free[pos - 1], free[pos]
		out[ys, x] = a[np.where(ys - above <= below - ys, above, below), x]
	return out


def row_fill(a, hole):
	return np.swapaxes(column_fill(np.swapaxes(a, 0, 1), hole.T), 0, 1)


def blocky_noise(shape, cell, rng):
	"""Uniform noise in `cell`-sized blocks."""
	h, w = shape
	n = rng.random((h // cell + 1, w // cell + 1))
	return np.kron(n, np.ones((cell, cell)))[:h, :w]


def save(name, a, alpha=None):
	a = np.clip(np.round(a), 0, 255).astype(np.uint8)
	if alpha is not None:
		alpha = np.clip(np.round(alpha * 255), 0, 255).astype(np.uint8)
		a = np.dstack([a, alpha])
	Image.fromarray(a).save(os.path.join(OUT, name))


def debug(name, a):
	if DEBUG:
		Image.fromarray(np.clip(np.round(a), 0, 255).astype(np.uint8)).save(os.path.join(DEBUG, name))


