# The night outside. The sky becomes a hole in the plate; behind it go a
# still sky (SKY) and the clouds, as a density map that repeats sideways.

SKY = (1384, 40, 1672, 222)
MOON = (1540, 200)
SEAM = 40
CLOUDS_FROM = 104


def split_sky(a):
	x0, y0, x1, y1 = SKY
	crop = a[y0:y1, x0:x1]
	l = lum(crop)
	moon = (l > 62) & (np.hypot(*np.mgrid[y0:y1, x0:x1][::-1] - np.array(MOON)[:, None, None]) < 16)
	moon = ndimage.binary_dilation(moon, iterations=1)
	sky = (l >= 17.5) | moon
	sky = ndimage.binary_opening(sky, iterations=1) | moon
	# The clear sky of each row: the darkest sky pixels of it.
	base = np.zeros((y1 - y0, 3))
	for y in range(y1 - y0):
		row = crop[y][sky[y] & ~moon[y]]
		if len(row) < 12:
			base[y] = np.nan
			continue
		rl = lum(row)
		base[y] = row[rl <= np.percentile(rl, 30)].mean(0)
	ys = np.arange(len(base))
	good = ~np.isnan(base[:, 0])
	for c in range(3):
		base[:, c] = np.interp(ys, ys[good], base[good, c])
		base[:, c] = ndimage.median_filter(base[:, c], 9, mode="nearest")
	still = np.repeat(base[:, None, :], x1 - x0, axis=1)
	still[moon] = crop[moon]
	# How much cloud there is on each pixel: 0, thin or thick.
	hidden = ~sky | ndimage.binary_dilation(moon, iterations=2)
	over = row_fill((l - lum(base)[:, None])[..., None], hidden)[..., 0]
	over = ndimage.median_filter(over, 5)
	density = np.where(over > 6.5, 1.0, np.where(over > 3.0, 0.5, 0.0))
	# No specks, and nothing to drift under the eaves or where the hills begin.
	labels, n = ndimage.label(density > 0)
	sizes = ndimage.sum(density > 0, labels, range(1, n + 1))
	density[np.isin(labels, np.nonzero(sizes < 40)[0] + 1)] = 0.0
	density[:CLOUDS_FROM - y0] = 0.0
	density[-8:] = 0.0
	# Make it repeat: the last SEAM columns give way to the ones that would
	# come before the first, picked block by block instead of blended.
	rng = np.random.default_rng(3)
	w = density.shape[1]
	pick = blocky_noise(density.shape, 6, rng)[:, :SEAM] < np.linspace(0, 1, SEAM)[None, :]
	tile = density[:, :w - SEAM].copy()
	tile[:, :SEAM] = np.where(pick, density[:, :SEAM], density[:, w - SEAM:])
	full = np.zeros(a.shape[:2], bool)
	full[y0:y1, x0:x1] = sky
	return still, tile, full


